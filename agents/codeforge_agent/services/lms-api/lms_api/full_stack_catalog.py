def _problems(technology, language, questions):
    problems = []
    for topic, items in questions.items():
        topic_slug = slugify(topic)
        for order, (name, question, correct, wrong, explanation) in enumerate(items, start=1):
            problems.append({
                "technology": technology, "topic": topic_slug, "name": name,
                "slug": f"{technology}-{slugify(name)}", "description": question,
                "input_format": "There is no input for this question.",
                "output_format": "Choose the option you believe is correct.",
                "constraints": "None.", "examples": [], "language": language, "language_id": None,
                "question_type": "mcq",
                "mcq_options": dict(zip("ABCD", [correct, *wrong])), "mcq_correct_key": "A",
                "mcq_explanation": explanation,
                "difficulty": topic_difficulty(technology, topic_slug), "order": order,
            })
    return problems


